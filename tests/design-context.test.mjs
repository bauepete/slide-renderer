import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'
import { rendererDesignRules, syncRendererMetadata, syncCourseDesignContext } from '../tooling/design-context.mjs'

const packageRoot = fileURLToPath(new URL('../', import.meta.url))
const design = readFileSync(join(packageRoot, 'DESIGN.md'), 'utf8')
const metadata = JSON.parse(readFileSync(join(packageRoot, '.impeccable/design.json'), 'utf8'))

function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), 'design-context-'))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const rendererRoot = join(root, 'renderer')
  const courseRoot = join(root, 'another-course')
  mkdirSync(join(rendererRoot, '.impeccable'), { recursive: true })
  mkdirSync(join(courseRoot, 'docs'), { recursive: true })
  writeFileSync(join(rendererRoot, 'DESIGN.md'), design)
  writeFileSync(join(rendererRoot, '.impeccable/design.json'), JSON.stringify(metadata))
  writeFileSync(join(rendererRoot, 'package.json'), '{"name":"slidev-addon-renderer","version":"1.0.1"}')
  writeFileSync(join(courseRoot, 'docs/presentation-policy.md'), '# Example policy\n\nKeep image descriptions meaningful.\n\n## Audience\n\nReaders of this course need complete captions. See [preparation](preparation.md?format=html#captions).\n\n### Caption detail\n\nPreserve the course terminology.\n')
  return { rendererRoot, courseRoot }
}

test('renderer narrative matches its canonical specification and contains no course policy', () => {
  assert.deepEqual(metadata.narrative.rules, rendererDesignRules(design))
  assert(!metadata.narrative.rules.some(rule => rule.name === 'Photography and representation'))
  assert.doesNotMatch(JSON.stringify(metadata), /Prologue|season number|episode-workflow\.md/)
  assert.equal(metadata.narrative.rules.find(rule => rule.name === 'Opening title slide').body,
    'The opening Title slide displays the presentation title and optional subtitle. Use the Title layout below, with the course-supplied title as the main heading. A wrapping Title heading grows upward from its usual lower edge, keeping the subtitle clear and retaining the 100 px type size.')
})

test('course context retains renderer tokens and specimens while rebasing links and adding local policy', t => {
  const options = fixture(t)
  assert.deepEqual(syncCourseDesignContext(options), ['DESIGN.md', '.impeccable/design.json'])
  const generated = readFileSync(join(options.courseRoot, 'DESIGN.md'), 'utf8')
  assert.equal(generated.match(/^---\n[\s\S]+?\n---/)[0], design.match(/^---\n[\s\S]+?\n---/)[0])
  assert.match(generated, /GENERATED by slidev-addon-renderer/)
  assert.match(generated, /\[preparation\]\(docs\/preparation\.md\?format=html#captions\)/)
  assert.match(generated, /Keep image descriptions meaningful/)
  assert.match(generated, /#### Caption detail\n\nPreserve the course terminology/)
  assert.match(generated, /`\.\.\/renderer\/assets\/SlideLayoutTemplate\/template-paper\.jpg`/)
  const data = JSON.parse(readFileSync(join(options.courseRoot, '.impeccable/design.json')))
  assert.deepEqual(data.components, metadata.components)
  assert.deepEqual(data.extensions, metadata.extensions)
  assert.equal(data.generatedFrom.renderer.version, '1.0.1')
  assert.equal(data.narrative.rules.at(-1).name, 'Audience')
  assert.match(data.narrative.rules.at(-1).body, /docs\/preparation\.md/)
  assert.match(data.narrative.rules.at(-1).body, /Preserve the course terminology/)
  assert.deepEqual(syncCourseDesignContext(options), [], 'regeneration must be idempotent')
})

test('check detects policy or package changes without rewriting generated files', t => {
  const options = fixture(t)
  syncCourseDesignContext(options)
  const file = join(options.courseRoot, 'DESIGN.md')
  const before = readFileSync(file)
  writeFileSync(join(options.courseRoot, 'docs/presentation-policy.md'), '# Policy\n\n## Audience\n\nChanged policy.\n')
  assert.throws(() => syncCourseDesignContext({ ...options, check: true }), /stale/)
  assert.deepEqual(readFileSync(file), before)
  syncCourseDesignContext(options)
  assert.deepEqual(syncCourseDesignContext({ ...options, check: true }), [])
  writeFileSync(join(options.rendererRoot, 'package.json'), '{"name":"slidev-addon-renderer","version":"2.0.0"}')
  assert.throws(() => syncCourseDesignContext({ ...options, check: true }), /stale/)
})

test('renderer metadata refresh preserves curated specimens and repairs narrative drift', t => {
  const { rendererRoot } = fixture(t)
  const file = join(rendererRoot, '.impeccable/design.json')
  writeFileSync(file, JSON.stringify({ ...metadata, narrative: { ...metadata.narrative, rules: [] } }))
  assert.throws(() => syncRendererMetadata({ root: rendererRoot, check: true }), /stale/)
  syncRendererMetadata({ root: rendererRoot })
  const updated = JSON.parse(readFileSync(file))
  assert.deepEqual(updated.components, metadata.components)
  assert.deepEqual(updated.narrative.rules, metadata.narrative.rules)
  assert.deepEqual(syncRendererMetadata({ root: rendererRoot, check: true }), [])
})

test('course policy cannot escape its project root', t => {
  assert.throws(() => syncCourseDesignContext({ ...fixture(t), policyPath: '../outside.md' }), /inside the course/)
})
